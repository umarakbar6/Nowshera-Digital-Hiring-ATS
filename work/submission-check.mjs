import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const html=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../public/style.css',import.meta.url),'utf8')+readFileSync(new URL('../public/theme.css',import.meta.url),'utf8');
const js=readFileSync(new URL('../public/app.js',import.meta.url),'utf8');
const schema=readFileSync(new URL('../database/schema.sql',import.meta.url),'utf8');
const manifest=readFileSync(new URL('../PROJECT-FILE-MANIFEST.md',import.meta.url),'utf8');
assert.match(html,/name="viewport"/,'responsive viewport metadata');
assert.match(html,/theme\.css/,'visual theme is linked');
assert.match(css,/@media\(max-width:700px\)/,'mobile breakpoint exists');
assert.match(css,/\.modalback/,'modal styling exists');
assert.doesNotMatch(css,/fonts\.googleapis\.com/,'no remote font dependency');
for(const surface of ['Job openings','My applications','My messages','My CV','Overview','Recruiters','Email outbox','One n8n hiring workflow','AI CV summary'])assert.ok(js.includes(surface),`missing interface surface: ${surface}`);
for(const action of ['application-detail','schedule','withdraw','toggle-recruiter','retry-ai'])assert.ok(js.includes(action),`missing UI action: ${action}`);
assert.ok(js.includes('aria-modal="true"'),'modal accessibility metadata');
const workflow=JSON.parse(readFileSync(new URL('../n8n/nowshera-complete-automation.json',import.meta.url),'utf8'));
assert.equal(workflow.nodes.filter(n=>['n8n-nodes-base.webhook','n8n-nodes-base.scheduleTrigger'].includes(n.type)).length,3,'single workflow contains three triggers');
assert.ok(workflow.nodes.some(n=>n.name==='Hiring Email Webhook'),'hiring email trigger exists');
assert.ok(workflow.nodes.some(n=>n.name==='Every 15 Minutes'),'scheduled reminder trigger exists');
assert.ok(workflow.nodes.some(n=>n.name==='AI Summary Webhook'),'AI summary trigger exists');
assert.equal(workflow.nodes.filter(n=>n.type==='n8n-nodes-base.gmail').length,2,'both Gmail delivery nodes exist');
assert.ok(workflow.nodes.some(n=>n.name==='Generate Summary with Gemini'),'AI model step exists');
assert.ok(workflow.nodes.some(n=>n.name==='Save AI Result or Failure'),'success and failure callback exists');
assert.ok(workflow.nodes.some(n=>n.onError==='continueRegularOutput'),'AI errors continue to failure callback');
assert.doesNotMatch(js,/GEMINI_API_KEY|generativelanguage\.googleapis/,'AI secret and provider are absent from browser code');
for(const table of ['users','cvs','jobs','job_recruiters','applications','interviews','sessions','invitations','emails'])assert.match(schema,new RegExp(`CREATE TABLE ${table}\\b`),`database schema documents ${table}`);
for(const file of ['server.mjs','database/schema.sql','public/app.js','n8n/nowshera-complete-automation.json','work/test.mjs'])assert.ok(manifest.includes('`'+file+'`'),`manifest documents ${file}`);
console.log('Submission UI checks passed.');
